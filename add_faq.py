def build_faq_jsonld(items):
    main_entity = [
        {
            "@type": "Question",
            "name": q,
            "acceptedAnswer": {"@type": "Answer", "text": a},
        }
        for q, a in items
    ]
    payload = {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": main_entity,
    }
    return (
        '<script type="application/ld+json">\n'
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + "\n</script>\n"
    )


def build_faq_section(items):
    blocks = []
    for q, a in items:
        blocks.append(f"    <h3>Q. {q}</h3>\n    <p>{a}</p>")
    body = "\n".join(blocks)
    return f'\n    <h2 id="faq">よくある質問</h2>\n{body}\n'


def build_toc_li():
    return '    <li><a href="#faq" class="hover:underline underline-offset-2">よくある質問</a></li>\n'


def process_file(slug):
    path = BASE / slug / "index.html"
    content = path.read_text(encoding="utf-8")
    items = FAQ_DATA[slug]

    # 1. Insert FAQPage JSON-LD before </head>
    faq_script = build_faq_jsonld(items)
    if "FAQPage" in content:
        print(f"  SKIP (already has FAQPage): {slug}")
        return
    if "</head>" not in content:
        print(f"  ERROR: </head> not found in {slug}")
        return
    content = content.replace("</head>", faq_script + "</head>", 1)

    # 2. Insert TOC <li> before the last </ol>\n</nav> (first nav = TOC)
    toc_li = build_toc_li()
    m = re.search(r'(<ol class="list-decimal[^"]*"[^>]*>)(.*?)(</ol>)', content, re.DOTALL)
    if not m:
        print(f"  ERROR: TOC <ol> not found in {slug}")
        return
    new_ol = m.group(1) + m.group(2) + toc_li + m.group(3)
    content = content[: m.start()] + new_ol + content[m.end():]

    # 3. Insert visible FAQ section before closing "  </div>\n</article>"
    faq_section = build_faq_section(items)
    target = "\n  </div>\n</article>"
    if target not in content:
        print(f"  ERROR: article closing not found in {slug}")
        return
    content = content.replace(target, faq_section + target, 1)

    path.write_text(content, encoding="utf-8")
    print(f"  OK: {slug}")


for slug in FAQ_DATA:
    process_file(slug)

print("Done.")
